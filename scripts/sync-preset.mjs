#!/usr/bin/env node
/**
 * Regenerate cordis.patch.yml from the CURRENT dsh `preset-standard` preset.
 *
 * Why this exists:
 *   On dsh web profiles the live compaction engine is a nested row inside the
 *   `preset-standard` agent preset (a `cordis:group` with isolate). No patch
 *   layer can address a nested row by id, and the top-level `compaction-basic`
 *   row is a disabled shell — patching it by name does nothing. The only
 *   supported fallback is a full-snapshot override of the preset itself
 *   (billion-context calls this "#2474"), so the whole preset config is copied
 *   here and only the engine line is swapped.
 *
 * Consequence (the thing worth remembering):
 *   The snapshot is PINNED to a dsh version. After upgrading dsh, the preset
 *   may have gained or changed plugins; until this script is re-run the plugin
 *   silently keeps serving the OLD preset shape. `--check` reports that drift.
 *
 * Usage:
 *   node scripts/sync-preset.mjs            # rewrite cordis.patch.yml
 *   node scripts/sync-preset.mjs --check    # exit 1 if the snapshot is stale
 *   node scripts/sync-preset.mjs --profile web
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const PATCH_FILE = join(ROOT, 'cordis.patch.yml');

const PRESET = 'preset-standard';
const ENGINE = 'dsh-compaction-ledger';
const FOREIGN_INJECT = /biliBasicCompactionPolicy/;

const argv = process.argv.slice(2);
const checkOnly = argv.includes('--check');
const profileAt = argv.indexOf('--profile');
const profile = profileAt >= 0 ? argv[profileAt + 1] : 'web';

function dshVersion() {
  try {
    return execFileSync('dsh', ['--version'], { encoding: 'utf8' }).trim().split('\n').pop().trim();
  } catch {
    return 'unknown';
  }
}

function dumpConfig() {
  return execFileSync('dsh', ['--profile', profile, '--dump-config'], {
    encoding: 'utf8',
    maxBuffer: 64 << 20,
  });
}

/** Cut the single top-level entry out of the dumped YAML. */
function slicePreset(text) {
  const lines = text.split('\n');
  const start = lines.indexOf(`- id: ${PRESET}`);
  if (start < 0) throw new Error(`entry "- id: ${PRESET}" not found in --dump-config output`);
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i += 1) {
    if (/^- id: |^# == /.test(lines[i])) {
      end = i;
      break;
    }
  }
  return lines.slice(start, end);
}

/**
 * Remove injections contributed by other bundles (billion-context gates every
 * preset with `inject: [biliBasicCompactionPolicy]`). The snapshot must stand
 * on its own, otherwise boot fails the moment bili is uninstalled.
 */
function sanitize(block) {
  const out = [];
  for (let i = 0; i < block.length; i += 1) {
    if (/^  inject:\s*$/.test(block[i])) {
      let j = i + 1;
      while (j < block.length && /^\s+- /.test(block[j])) j += 1;
      i = j - 1;
      continue;
    }
    if (FOREIGN_INJECT.test(block[i])) continue;
    out.push(block[i]);
  }
  return out;
}

/** Point the preset's nested compaction row at this package. */
function swapEngine(block) {
  const at = block.findIndex((l) => /^\s*- id: compaction-basic\s*$/.test(l));
  if (at < 0) throw new Error('nested "- id: compaction-basic" row not found inside the preset');
  const nameAt = block.findIndex(
    (l, i) => i > at && /^\s*name:\s*['"]?@deepseek-ai\/dsh-compaction-basic['"]?\s*$/.test(l),
  );
  if (nameAt < 0) throw new Error('nested compaction-basic row has no @deepseek-ai/dsh-compaction-basic name line');
  const indent = block[nameAt].match(/^\s*/)[0];
  const next = [...block];
  next[nameAt] = `${indent}name: ${ENGINE}`;
  return next;
}

function render(block, version) {
  const header = [
    '# AUTO-GENERATED by scripts/sync-preset.mjs — DO NOT EDIT BY HAND.',
    `# Snapshot of the \`${PRESET}\` preset taken from ${profile} profile, dsh ${version}.`,
    '#',
    '# WHY: on dsh web profiles the live compaction engine is a nested row inside',
    '# `preset-standard` (a cordis:group with isolate). No patch layer can address a',
    '# nested row by id, and the top-level `compaction-basic` row is a disabled shell,',
    '# so patching that id by name is a no-op. Full-snapshot override of the preset is',
    '# the supported fallback (billion-context calls it "#2474").',
    '#',
    '# AFTER UPGRADING DSH: run `npm run sync:preset`, bump the version, repack and',
    '# reinstall. `npm run check:preset` exits non-zero when this snapshot is stale.',
    `# Snapshot-DSH-Version: ${version}`,
    `# Snapshot-Date: ${new Date().toISOString()}`,
  ];
  return `${header.join('\n')}\n${block.join('\n')}\n`;
}

const version = dshVersion();
const block = swapEngine(sanitize(slicePreset(dumpConfig())));
const snapshot = render(block, version);

if (checkOnly) {
  let current = '';
  try {
    current = readFileSync(PATCH_FILE, 'utf8');
  } catch {
    current = '';
  }
  const strip = (s) => s.replace(/^# Snapshot-Date:.*$/gm, '').trimEnd();
  if (strip(current) === strip(snapshot)) {
    console.log(`preset snapshot is current (dsh ${version}, ${profile} profile)`);
    process.exit(0);
  }
  console.error('preset snapshot is STALE — run: npm run sync:preset');
  console.error(`  dsh version now: ${version}`);
  process.exit(1);
}

writeFileSync(PATCH_FILE, snapshot);
const lines = block.length;
const engineLine = block.find((l) => l.includes(ENGINE));
console.log(`wrote ${PATCH_FILE}`);
console.log(`  dsh ${version} / ${profile} / ${PRESET}: ${lines} lines`);
console.log(`  engine row: ${engineLine.trim()}`);
